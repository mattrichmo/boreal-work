export const validateCommandFlags = (args: ParsedArgs, definition: CommandDefinition): void => {
  const allowedFlags = new Map<string, FlagDefinition>();
  for (const entry of [...GLOBAL_FLAGS, ...definition.flags]) {
    allowedFlags.set(entry.name, entry);
  }

  for (const [name, values] of args.flags.entries()) {
    const definitionForFlag = allowedFlags.get(name);
    if (!definitionForFlag) {
      const didYouMean = nearestRegisteredFlag(name, allowedFlags);
      throw new BorealError(
        "BOREAL_INVALID_INPUT",
        `Unknown flag --${name} for bwrk ${commandPath(definition)}${didYouMean ? `. Did you mean --${didYouMean}?` : ""}`,
        {
          command: definition.path,
          flag: name,
          ...(didYouMean ? { didYouMean: `--${didYouMean}` } : {}),
        },
      );
    }
    if (!definitionForFlag.repeatable && values.length > 1) {
      throw new BorealError(
        "BOREAL_INVALID_INPUT",
        `Flag --${name} may only be provided once for bwrk ${commandPath(definition)}`,
        {
          command: definition.path,
          flag: name,
        },
      );
    }
    if (definitionForFlag.type === "boolean") {
      const invalidValue = values.find((value) => value !== "true" && value !== "false");
      if (invalidValue) {
        throw new BorealError(
          "BOREAL_INVALID_INPUT",
          `Flag --${name} expects a boolean value for bwrk ${commandPath(definition)}`,
          {
            command: definition.path,
            flag: name,
            value: invalidValue,
          },
        );
      }
    }
  }

  const positionals = args.command.slice(definition.path.length);
  const positionalRule = definition.positionals ?? { label: "arguments", min: 0, max: 0 };
  if (positionals.length < positionalRule.min) {
    throw new BorealError(
      "BOREAL_INVALID_INPUT",
      `Missing ${positionalRule.label} for bwrk ${commandPath(definition)}`,
      {
        command: definition.path,
        expected: positionalRule,
        actual: positionals.length,
      },
    );
  }
  if (positionalRule.max !== undefined && positionals.length > positionalRule.max) {
    throw new BorealError(
      "BOREAL_INVALID_INPUT",
      `Unexpected argument for bwrk ${commandPath(definition)}`,
      {
        command: definition.path,
        expected: positionalRule,
        actual: positionals,
      },
    );
  }
};

function nearestRegisteredFlag(name: string, allowedFlags: ReadonlyMap<string, FlagDefinition>): string | undefined {
  const aliases = flagAliasCandidates(name).filter((candidate) => allowedFlags.has(candidate));
  if (aliases[0]) {
    return aliases[0];
  }
  const candidates = [...allowedFlags.keys()];
  const ranked = candidates
    .map((candidate) => ({ candidate, distance: levenshteinDistance(name, candidate) }))
    .sort((left, right) => left.distance - right.distance || left.candidate.localeCompare(right.candidate));
  const nearest = ranked[0];
  return nearest && nearest.distance <= Math.max(3, Math.ceil(Math.max(name.length, nearest.candidate.length) / 2))
    ? nearest.candidate
    : undefined;
}

function flagAliasCandidates(name: string): readonly string[] {
  switch (name) {
    case "parent":
      return ["container"];
    case "pr":
    case "prio":
      return ["priority"];
    default:
      return [];
  }
}

function levenshteinDistance(left: string, right: string): number {
  let previous: number[] = Array.from({ length: right.length + 1 }, (_, index) => index);
  for (let leftIndex = 1; leftIndex <= left.length; leftIndex += 1) {
    const current: number[] = [leftIndex];
    for (let rightIndex = 1; rightIndex <= right.length; rightIndex += 1) {
      const substitutionCost = left[leftIndex - 1] === right[rightIndex - 1] ? 0 : 1;
      current[rightIndex] = Math.min(
        (current[rightIndex - 1] ?? leftIndex) + 1,
        (previous[rightIndex] ?? rightIndex) + 1,
        (previous[rightIndex - 1] ?? rightIndex - 1) + substitutionCost
      );
    }
    previous = current;
  }
  return previous[right.length] ?? 0;
}
