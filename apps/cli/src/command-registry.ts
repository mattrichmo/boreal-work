const commandMatches = (command: readonly string[], definition: CommandDefinition): boolean => {
  if (command.length < definition.path.length) {
    return false;
  }
  return definition.path.every((segment, index) => command[index] === segment);
};

export const findCommandDefinition = (command: readonly string[]): CommandDefinition | undefined =>
  COMMAND_DEFINITIONS.filter((definition) => commandMatches(command, definition)).sort(
    (a, b) => b.path.length - a.path.length,
  )[0];

export const commandPath = (definition: CommandDefinition): string => definition.path.join(" ");

export function commandBehavior(definition: CommandDefinition): CommandBehaviorMetadata {
  const command = commandPath(definition);
  const behavior = COMMAND_BEHAVIOR[command];
  if (!behavior) {
    throw new BorealError("BOREAL_INVARIANT", "Command is missing behavior metadata", { command });
  }
  return behavior;
}

export function validateCommandBehaviorMetadata(): void {
  const commands = new Set(COMMAND_DEFINITIONS.map(commandPath));
  const metadataCommands = new Set(Object.keys(COMMAND_BEHAVIOR));
  const missing = [...commands].filter((command) => !metadataCommands.has(command));
  const extra = [...metadataCommands].filter((command) => !commands.has(command));
  const emptyExamples = COMMAND_DEFINITIONS.map(commandPath).filter((command) => COMMAND_BEHAVIOR[command]?.examples.length === 0);
  if (missing.length > 0 || extra.length > 0 || emptyExamples.length > 0) {
    throw new BorealError("BOREAL_INVARIANT", "Command behavior metadata is out of sync", {
      missing,
      extra,
      emptyExamples,
    });
  }
}

export function registryValueFlagNames(): ReadonlySet<string> {
  return new Set(
    [...GLOBAL_FLAGS, ...COMMAND_DEFINITIONS.flatMap((definition) => definition.flags)]
      .filter((definition) => definition.type === "value")
      .map((definition) => definition.name)
  );
}

export function isTopLevelGroup(name: string): boolean {
  return COMMAND_DEFINITIONS.some((definition) => definition.path[0] === name);
}

