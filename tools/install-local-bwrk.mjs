#!/usr/bin/env node
import { spawnSync } from "node:child_process";
import { chmod, mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { delimiter, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const defaultBinDir = join(process.env.HOME ?? "", ".local", "bin");
const binDir = resolve(flagValue("--bin-dir") ?? process.env.BOREAL_BIN_DIR ?? defaultBinDir);
const sourceEntrypoint = join(repoRoot, "apps", "cli", "src", "index.ts");
const tsconfig = join(repoRoot, "tsconfig.base.json");
const tsxEntrypoint = join(repoRoot, "node_modules", ".bin", "tsx");
const shimPath = join(binDir, "bwrk");

if (!existsSync(sourceEntrypoint)) {
  fail(`Missing source CLI at ${sourceEntrypoint}. Run from a Boreal source checkout.`);
}
if (!existsSync(tsconfig)) {
  fail(`Missing TypeScript config at ${tsconfig}. Run from a Boreal source checkout.`);
}
if (!existsSync(tsxEntrypoint)) {
  fail(`Missing tsx runner at ${tsxEntrypoint}. Run pnpm install first.`);
}

const entrypoint = await readFile(sourceEntrypoint, "utf8");
if (!entrypoint.startsWith("#!/usr/bin/env node")) {
  fail(`Source CLI does not look executable: ${sourceEntrypoint}`);
}

await mkdir(binDir, { recursive: true });
await writeFile(
  shimPath,
  [
    "#!/bin/sh",
    "# Local Boreal Work CLI shim. Generated by pnpm install:local.",
    `exec ${shellQuote(tsxEntrypoint)} --tsconfig ${shellQuote(tsconfig)} ${shellQuote(sourceEntrypoint)} "$@"`,
    ""
  ].join("\n"),
  "utf8"
);
await chmod(shimPath, 0o755);

const verification = spawnSync(shimPath, ["--version"], { encoding: "utf8" });
if (verification.status !== 0) {
  fail(
    [
      `Installed shim did not pass version verification: ${shimPath} --version`,
      verification.stderr?.trim(),
      verification.stdout?.trim()
    ]
      .filter(Boolean)
      .join("\n")
  );
}

const pathContainsBinDir = pathEntries(process.env.PATH ?? "").some((entry) => entry === binDir);

console.log(`Installed local bwrk shim: ${shimPath}`);
console.log(`Target CLI: ${sourceEntrypoint}`);
console.log(`Runner: ${tsxEntrypoint}`);
console.log(`Package verification: ${verification.stdout.trim()}`);
if (pathContainsBinDir) {
  console.log("PATH check: ok");
  console.log("Verify with: bwrk --version");
} else {
  console.log(`PATH check: ${binDir} is not on PATH`);
  console.log(`Add it with: export PATH=${shellQuote(binDir)}:$PATH`);
  console.log(`Verify now with: ${shellQuote(shimPath)} --version`);
}

function flagValue(name) {
  const index = process.argv.indexOf(name);
  if (index < 0) {
    return undefined;
  }
  const value = process.argv[index + 1];
  if (!value || value.startsWith("--")) {
    fail(`${name} requires a value`);
  }
  return value;
}

function shellQuote(value) {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

function pathEntries(value) {
  return value
    .split(delimiter)
    .map((entry) => entry.trim())
    .filter(Boolean)
    .map((entry) => resolve(entry));
}

function fail(message) {
  console.error(message);
  process.exit(1);
}
